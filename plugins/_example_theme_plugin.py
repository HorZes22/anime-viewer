# -*- coding: utf-8 -*-
"""
ПРИМЕР плагина с собственной темой оформления (файл начинается с «_», поэтому
приложение его НЕ подключает — скопируйте под другим именем, например
my_theme.py, и тема появится в «Оформлении»).

Что показывает пример:

  * themes() возвращает словарь {код темы: палитра};
  * цвета можно задавать «человеческими» именами (background, surface, text_muted,
    hover, selected) — приложение разложит их по своим ключам;
  * необязательные ключи: gradient (пара цветов — вертикальный градиент окна) и
    font_family (имя шрифта; свои .ttf кладите в assets/fonts);
  * акцент темы задаётся ключом accent; если его не указать, останется текущий.
"""

from main import Plugin


class ThemeExamplePlugin(Plugin):
    name = "theme-example"
    title = "Пример своей темы"
    version = "1.0"
    author = "Anime Viewer"
    description = "Добавляет тему «Закат»: показывает, как плагин задаёт оформление"

    def themes(self):
        return {
            # код темы (латиницей, без пробелов) — по нему тема выбирается в настройках
            "sunset-example": {
                "title": "Закат (пример плагина)",

                # цвета: можно и «человеческими» именами (background/surface/…),
                # и ключами приложения (bg/panel/card/…)
                "background": "#1a1016",
                "surface": "#241a22",
                "surface_alt": "#2b1f29",       # карточки
                "hover": "#33242f",             # карточка под курсором
                "video": "#120a10",             # область видео и страниц
                "text": "#ffeee8",
                "text_muted": "#b08f9c",
                "outline": "#3a2b34",           # рамки и разделители
                "field": "#241a22",             # поля ввода
                "field_focus": "#2b1f29",

                # акцент: по нему считаются оттенки ховера и цвет текста поверх
                "accent": "#ff7a59",

                # необязательно: вертикальный градиент фона окна
                "gradient": ["#241521", "#150d13"],

                # необязательно: свой шрифт (файл .ttf положите в assets/fonts)
                # "font_family": "Inter",
            }
        }
